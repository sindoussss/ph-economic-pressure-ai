"""Canonical filesystem locations and shared backtest constants.

Every module that reads or writes a benchmark artifact used to re-derive the
directory from `Path(__file__)`, in thirteen places, and `min_train=24` appeared
as a bare default in a dozen more. Duplicated constants drift: the panel method
list was copied into `run.py`, drifted from `audit.PANEL_METHODS`, and silently
produced a frozen report whose efficiency panel omitted a baseline the audit
included. This module exists so there is one place to change.

Import the names; do not re-derive the paths.
"""
from __future__ import annotations

from pathlib import Path

#: `ph_economic_ai/benchmark/`
BENCHMARK_DIR = Path(__file__).resolve().parent

#: Frozen inputs (committed CSVs — the benchmark reads only these).
DATA_DIR = BENCHMARK_DIR / 'data'

#: Generated outputs (reports, tables, figures). Regenerated by `benchmark.run`.
ARTIFACTS_DIR = BENCHMARK_DIR / 'artifacts'
FIGURES_DIR = ARTIFACTS_DIR / 'figures'

#: The frozen report every downstream consumer reads — including the app, which
#: must never hardcode a verdict it could read from here.
ACCURACY_REPORT = ARTIFACTS_DIR / 'accuracy_report.json'

#: Repository-root `docs/img/`, where publication figures are mirrored.
DOCS_IMG_DIR = BENCHMARK_DIR.parents[1] / 'docs' / 'img'

#: Minimum training observations before the first walk-forward prediction.
#: Two years of monthly data: enough for a seasonal baseline to exist at all.
MIN_TRAIN = 24


def artifact(name: str) -> Path:
    """Path to a named artifact, e.g. `artifact('power.json')`."""
    return ARTIFACTS_DIR / name


def data(name: str) -> Path:
    """Path to a named frozen input, e.g. `data('features_monthly.csv')`."""
    return DATA_DIR / name
